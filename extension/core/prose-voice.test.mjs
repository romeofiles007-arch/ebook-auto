/**
 * คำสั่งเขียนต้องมีคนถาม ไม่ใช่มีใบสั่ง
 *
 * อาการที่เจอในเล่มจริง: ประโยคอย่าง "เดินหน้า — ขับแผนต่อได้เมื่อข้อมูลจริงและเงื่อนไขสำคัญสนับสนุน"
 * ไม่มีคน ไม่มีของ อ่านจบประโยคแล้วผู้อ่านไม่ได้อะไรกลับไป
 *
 * ต้นเหตุไม่ใช่โมเดลเขียนไม่เป็น แต่เป็นเพราะเราไม่เคยถามอะไรมันเลย เราส่งใบสั่งงานไปให้
 * (ข้อเสนอที่ต้องอธิบาย · ผลที่ต้องได้เมื่ออ่านจบ · ขอบเขตที่อยู่ตอนอื่น) ซึ่งเป็นภาษาวางแผน
 * ที่อีกโมเดลหนึ่งเขียนไว้ตอนวางสารบัญ โมเดลจึงขัดถ้อยคำของใบสั่งให้สวยแล้วส่งกลับมาเป็นเนื้อหา
 *
 * เทสต์นี้เฝ้าว่าใบสั่งยังถูกวางในฐานะ "โน้ตของคนเล่า" ไม่ใช่ "ข้อความที่ต้องขัดให้สวย"
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { proseBatch } from './editorial.js';

const build = (over = {}) => proseBatch({
  book: { language: 'th' },
  chapter: { n: 4, title: 'ความรัก', sections: [{ id: '4.1', title: 'ความรักปีนี้' }] },
  sections: [{
    id: '4.1',
    title: 'ความรักปีนี้',
    problem: 'ปีนี้ความรักฉันจะเป็นยังไง',
    claim: 'ปัญหาอยู่ที่ความคาดหวังที่ไม่ได้พูดออกมา',
    quota: 1800,
  }],
  context: '-',
  output: '-',
  voice: '-',
  ...over,
});

test('มีผู้อ่านตัวเป็น ๆ ถามคำถาม ไม่ใช่ใบสั่งงานลอย ๆ', () => {
  const p = build();
  assert.match(p, /มีผู้อ่านคนหนึ่งนั่งอยู่ตรงหน้าคุณ/, 'ต้องมีคนถามอยู่ในคำสั่ง');
  assert.match(p, /เขาถามว่า: ปีนี้ความรักฉันจะเป็นยังไง/, 'โจทย์ของตอนต้องมาในรูปคำถามของคน');
  assert.ok(!/หน้าที่รอบนี้: เขียนเนื้อหาตามสารบัญที่อนุมัติแล้ว/.test(p), 'หัวคำสั่งแบบใบสั่งงานต้องไม่กลับมา');
});

test('ช่องในใบสั่งพูดถึงผู้อ่าน ไม่ใช่พูดถึงเอกสาร', () => {
  const p = build();
  assert.match(p, /สิ่งที่เขาต้องเข้าใจกลับไป/);
  assert.match(p, /สิ่งที่เขาต้องทำได้หรือตัดสินใจได้หลังฟังจบ/);
  assert.ok(!/ข้อเสนอที่ต้องอธิบายพร้อมเหตุผล/.test(p), 'ภาษาวางแผนแบบเดิมต้องถูกถอดออกแล้ว');
  assert.ok(!/ผลที่ต้องได้เมื่ออ่านจบ/.test(p), 'ภาษาวางแผนแบบเดิมต้องถูกถอดออกแล้ว');
});

/**
 * ข้อสำคัญที่สุด — ถ้าไม่มีบรรทัดนี้ โมเดลจะลอกสำนวนของใบสั่งมาใช้เหมือนเดิม
 * ต่อให้เปลี่ยนชื่อช่องไปแล้วก็ตาม
 */
test('บอกตรง ๆ ว่าใบสั่งเป็นโน้ต ห้ามลอกสำนวนของมัน', () => {
  const p = build();
  assert.match(p, /คือโน้ตของคุณเอง ไม่ใช่ตัวอย่างสำนวน/);
  assert.match(p, /ห้ามลอกถ้อยคำหรือรูปประโยคของโน้ต/);
});

/**
 * "เขียนให้เป็นธรรมชาติ" เป็นคำสั่งที่โมเดลทำตามไม่ได้ เพราะมันคิดว่าตัวเองเป็นธรรมชาติอยู่แล้ว
 * ด่านสุดท้ายจึงต้องเป็นคำถามที่เอาไปตรวจประโยคทีละประโยคได้จริง
 */
test('ด่านสุดท้ายเป็นคำถามที่ตรวจได้ ไม่ใช่คำคุณศัพท์', () => {
  const p = build();
  assert.match(p, /ไม่มีทางหลุดออกจากปากคนที่กำลังเล่าเรื่องให้เพื่อนฟัง ให้เขียนประโยคนั้นใหม่/);
});

test('คำสั่งยังสั้นพอหลังเพิ่มกฎใหม่', () => {
  const p = build();
  assert.ok(p.length < 4000, `คำสั่งยาว ${p.length} ตัวอักษรตั้งแต่ยังไม่ใส่บริบทจริง`);
});

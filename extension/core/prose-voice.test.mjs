/**
 * คำสั่งเขียนต้องมีคนถาม ไม่ใช่มีใบสั่ง — และต้องไม่ผูกกับแนวหนังสือแนวใดแนวหนึ่ง
 *
 * อาการที่เจอในเล่มจริง: ประโยคอย่าง "เดินหน้า — ขับแผนต่อได้เมื่อข้อมูลจริงและเงื่อนไขสำคัญสนับสนุน"
 * ไม่มีคน ไม่มีของ อ่านจบประโยคแล้วผู้อ่านไม่ได้อะไรกลับไป
 *
 * ต้นเหตุไม่ใช่โมเดลเขียนไม่เป็น แต่เป็นเพราะเราไม่เคยถามอะไรมันเลย เราส่งใบสั่งงานไปให้
 * ซึ่งเป็นภาษาวางแผนที่อีกโมเดลหนึ่งเขียนไว้ตอนวางสารบัญ โมเดลจึงขัดถ้อยคำของใบสั่งให้สวย
 * แล้วส่งกลับมาเป็นเนื้อหา
 *
 * กับดักของการแก้เรื่องนี้คือการไปสั่งเสียงใหม่ทับลงไปทั้งเล่ม — ระบบทำหนังสือเจ็ดแนว
 * ตำราวิชาการกับเวิร์กบุ๊กไม่ได้ต้องการเสียงเดียวกับเล่มเล่าเรื่อง สั่ง "เล่าให้เพื่อนฟัง"
 * ทับทุกแนวก็แค่เปลี่ยนจากเสียงเดียวที่แข็ง เป็นเสียงเดียวที่กันเอง ซึ่งยังผิดอยู่ดี
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { proseBatch } from './editorial.js';

const build = (over = {}, chapterOver = {}) => proseBatch({
  book: { language: 'th' },
  chapter: { n: 4, title: 'บทสี่', sections: [{ id: '4.1', title: 'ตอนหนึ่ง' }], ...chapterOver },
  sections: [{
    id: '4.1',
    title: 'ตอนหนึ่ง',
    problem: 'เริ่มต้นยังไงดี',
    claim: 'เริ่มจากสิ่งที่วัดผลได้ก่อน',
    quota: 1800,
  }],
  context: '-',
  output: '-',
  voice: '-',
  ...over,
});

test('มีผู้อ่านตัวเป็น ๆ ถามคำถาม ไม่ใช่ใบสั่งงานลอย ๆ', () => {
  const p = build();
  assert.match(p, /มีผู้อ่านคนหนึ่งอยู่ตรงหน้าคุณ/, 'ต้องมีคนถามอยู่ในคำสั่ง');
  assert.match(p, /เขาถามว่า: เริ่มต้นยังไงดี/, 'โจทย์ของตอนต้องมาในรูปคำถามของคน');
  assert.ok(!/หน้าที่รอบนี้: เขียนเนื้อหาตามสารบัญที่อนุมัติแล้ว/.test(p), 'หัวคำสั่งแบบใบสั่งงานต้องไม่กลับมา');
});

test('ช่องในใบสั่งพูดถึงผู้อ่าน ไม่ใช่พูดถึงเอกสาร', () => {
  const p = build();
  assert.match(p, /สิ่งที่เขาต้องเข้าใจกลับไป/);
  assert.match(p, /สิ่งที่เขาต้องทำได้หรือตัดสินใจได้หลังฟังจบ/);
  assert.ok(!/ข้อเสนอที่ต้องอธิบายพร้อมเหตุผล/.test(p), 'ภาษาวางแผนแบบเดิมต้องถูกถอดออกแล้ว');
});

/**
 * ข้อสำคัญที่สุด — ถ้าไม่มีบรรทัดนี้ โมเดลจะลอกสำนวนของใบสั่งมาใช้เหมือนเดิม
 * ต่อให้เปลี่ยนชื่อช่องไปแล้วก็ตาม
 */
test('บอกตรง ๆ ว่าใบสั่งเป็นโน้ต ห้ามลอกสำนวนของมัน', () => {
  const p = build();
  assert.match(p, /คือโน้ตของคุณเอง ไม่ใช่ตัวอย่างสำนวน/);
  assert.match(p, /ห้ามลอกถ้อยคำหรือรูปประโยคของโน้ต/);
});

/**
 * "เขียนให้เป็นธรรมชาติ" เป็นคำสั่งที่โมเดลทำตามไม่ได้ เพราะมันคิดว่าตัวเองเป็นธรรมชาติอยู่แล้ว
 * ด่านสุดท้ายจึงต้องเป็นคำถามที่เอาไปตรวจประโยคทีละประโยคได้จริง และต้องชี้ที่ตัวอาการ
 * (ประโยคที่เป็นช่องในฟอร์มถูกขัดเงา) ไม่ใช่ชี้ที่สำนวนแบบใดแบบหนึ่ง
 */
test('ด่านสุดท้ายชี้ที่อาการ ไม่ใช่สั่งสำนวน', () => {
  const p = build();
  assert.match(p, /ยังเป็นช่องในใบสั่งที่ถูกขัดให้สวย/);
  assert.match(p, /ตัดไปใส่เล่มอื่นก็ไม่มีใครรู้/);
});

/**
 * ระบบทำหนังสือเจ็ดแนว คำสั่งกลางห้ามบังคับท่าของแนวใดแนวหนึ่ง
 * โดยเฉพาะข้อที่เคยเขียนไว้ว่า "อย่าเริ่มด้วยการนิยามศัพท์" ซึ่งขัดกับกฎของแนวตำราวิชาการ
 * ที่บังคับว่าศัพท์สำคัญต้องมีนิยามชัดตั้งแต่ครั้งแรกที่ปรากฏ
 */
test('คำสั่งกลางต้องไม่ผูกกับแนวหนังสือแนวใดแนวหนึ่ง', () => {
  const p = build();
  assert.ok(!/นิยามศัพท์/.test(p), 'ห้ามสั่งเรื่องการนิยามศัพท์ในคำสั่งกลาง แนวตำราวิชาการต้องนิยามได้');
  assert.ok(!/เล่าให้เพื่อนฟัง/.test(p), 'ห้ามบังคับสำนวนเล่าเรื่องกับทุกแนว');
  assert.ok(!/เหมือนคุยกัน|เป็นกันเอง/.test(p), 'ห้ามบังคับระดับความเป็นกันเองกับทุกแนว');
});

/**
 * register ถูกเลือกไว้ตั้งแต่ตอนวางสารบัญ พร้อมกฎว่าแนวไหนควรใช้ท่าไหน
 * แต่เดิมไม่มีโค้ดบรรทัดไหนอ่านมันเลย ทั้งเล่มจึงออกมาเสียงเดียวกันหมด
 */
test('ท่าประจำบทที่สารบัญเลือกไว้ ต้องไปถึงคนเขียน', () => {
  const a = build({}, { register: 'คู่มือลงมือ' });
  assert.match(a, /ท่าประจำบทนี้ — คู่มือลงมือ/);
  assert.match(a, /บอกว่าทำอะไร ทำอย่างไร และรู้ได้ยังไงว่าทำถูก/);

  const b = build({}, { register: 'แกะความเชื่อ' });
  assert.match(b, /แยกให้ชัดว่าส่วนไหนมีหลักฐาน/);
  assert.ok(!/ท่าประจำบทนี้ — คู่มือลงมือ/.test(b), 'คนละบทต้องได้คนละท่า');
});

test('ท่าประจำบทห้ามทับกฎของแนวหนังสือ', () => {
  const p = build({}, { register: 'เล่าเรื่องเดียวให้จบ' });
  assert.match(p, /ห้ามขัดกับข้อกำหนดของแนวหนังสือข้างบน/);
});

/**
 * สารบัญเก่าไม่มีฟิลด์นี้ และโมเดลพิมพ์ค่าเพี้ยนได้ — ไม่รู้จักท่าก็ไม่ต้องสั่งท่า
 * ปล่อยให้แนวหนังสือกับใบสั่งของตอนเป็นตัวกำหนด ดีกว่าเดาผิดแล้วไปทับกฎของแนว
 */
test('ไม่มีท่าหรือท่าเพี้ยน = ไม่สั่งท่า ไม่ใช่พัง', () => {
  for (const register of [undefined, '', 'ท่าที่ไม่มีในรายการ', null]) {
    const p = build({}, { register });
    assert.ok(!/ท่าประจำบทนี้/.test(p), `register=${register} ไม่ควรสั่งท่า`);
    assert.ok(!/undefined/.test(p), `register=${register} ทำให้มี undefined โผล่ใน prompt`);
  }
});

test('คำสั่งยังสั้นพอหลังเพิ่มกฎใหม่', () => {
  assert.ok(build({}, { register: 'คู่มือลงมือ' }).length < 4000);
});

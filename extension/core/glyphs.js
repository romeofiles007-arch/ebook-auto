/**
 * กันตัวอักษรที่ฟอนต์วาดไม่ได้ ไม่ให้กลายเป็นกล่องสี่เหลี่ยมในเล่มจริง
 *
 * อาการที่เจอในเล่มจริง: โมเดลวาดผังต้นไม้ด้วยตัวอักษรวาดกรอบ (─ │ ├ └)
 * และใช้อีโมจิวงกลมสีเป็นสัญลักษณ์สถานะ ทั้งสองอย่างไม่มีอยู่ในฟอนต์ไทยที่เล่มนี้ใช้
 * Typst จึงวาดเป็นกล่องเปล่าเรียงกันเป็นแถว ผู้อ่านเห็นเป็น □□□□□□ กลางประโยค
 * และไม่มีอะไรในระบบทักเลยสักจุดเดียว ตั้งแต่ตอนเขียนจนถึงตอนส่งออกไฟล์
 *
 * ชั้นนี้ทำสองอย่าง
 *   1. แปลงตัวที่แทนได้ให้เป็นตัวที่ฟอนต์มีจริง โดยรักษาความหมายไว้ให้มากที่สุด
 *   2. ตัวที่แทนไม่ได้ ให้ถอดทิ้งพร้อมรายงานกลับไป ไม่ปล่อยให้กลายเป็นกล่อง
 *
 * ตัวแทนทุกตัวในไฟล์นี้ถูกตรวจแล้วว่าฟอนต์ในเล่มวาดได้จริง ด้วย isDrawable()
 * ไม่ใช่เดาเอาว่าน่าจะมี
 */

import { isDrawable } from './font-coverage.js';

/**
 * ตัวอักษรวาดกรอบและบล็อก — โมเดลชอบใช้วาดผัง ตาราง และแท่งกราฟ
 * แปลงเป็นเครื่องหมายที่อ่านแล้วยังเข้าใจโครงเดิม ไม่ใช่ตัดทิ้งจนความหมายหาย
 */
const BOX_DRAWING = {
  '─': '—', // ─ เส้นนอน → em dash
  '━': '—',
  '│': '|', // │ เส้นตั้ง
  '┃': '|',
  '┌': ' ', // ┌ มุม — ไม่มีความหมายในข้อความที่ไหลตามบรรทัด
  '┐': ' ', // ┐
  '└': '-', // └ กิ่งสุดท้ายของผัง
  '┘': ' ', // ┘
  '├': '-', // ├ กิ่งกลางของผัง
  '┤': '-', // ┤
  '┬': '-', // ┬
  '┴': '-', // ┴
  '┼': '+', // ┼
  '█': '#', // █ แท่งกราฟทึบ
  '░': '.', // ░
  '▒': ':', // ▒
  '▓': '#', // ▓
  '■': '*', // ■
  '□': '*', // □
  '▪': '*', // ▪
  '●': '*', // ●
  '○': 'o', // ○
  '•': '•', // • ฟอนต์มีอยู่แล้ว ปล่อยผ่าน
  '▲': '^', // ▲ ลูกศรขึ้นในตารางเปรียบเทียบ
  '▼': 'v', // ▼
  '◆': '*', // ◆
  '◇': '*', // ◇
};

/**
 * เครื่องหมายถูก/ผิด — พบบ่อยที่สุดในเนื้อหาจริง (เจอ 51 จุดในเล่มที่เขียนไปแล้ว)
 * มักอยู่ในตารางเปรียบเทียบ ซึ่งถ้าถอดทิ้งเฉย ๆ ช่องนั้นจะว่างและอ่านผิดความหมายทันที
 */
const MARKS = {
  '✓': '(ใช่)',
  '✔': '(ใช่)',
  '☑': '(ใช่)',
  '✗': '(ไม่)',
  '✘': '(ไม่)',
  '☒': '(ไม่)',
};

/** อีโมจิที่ใช้เป็นสัญลักษณ์สถานะ — แปลงเป็นคำ เพราะสีคือความหมายทั้งหมดของมัน */
const STATUS_EMOJI = {
  '\u{1F7E2}': '(เขียว)',
  '\u{1F7E1}': '(เหลือง)',
  '\u{1F534}': '(แดง)',
  '\u{1F7E0}': '(ส้ม)',
  '\u{1F535}': '(น้ำเงิน)',
  '✅': '(ผ่าน)',
  '❌': '(ไม่ผ่าน)',
  '⚠️': '(ระวัง)',
  '⚠': '(ระวัง)',
  '⭐': '*',
  '\u{1F449}': '→',
  '\u{1F4A1}': '(ข้อสังเกต)',
  '\u{1F4CC}': '(สำคัญ)',
  '\u{1F4DD}': '(บันทึก)',
};

const MAP = { ...BOX_DRAWING, ...MARKS, ...STATUS_EMOJI };

/**
 * แปลงข้อความให้เหลือเฉพาะตัวอักษรที่พิมพ์ออกมาแล้วเห็นจริง
 *
 * @returns {{text: string, changes: Array<{ch: string, cp: number, to: string, n: number}>}}
 *   changes ใช้รายงานให้ผู้ใช้เห็นว่าอะไรถูกแตะบ้าง ไม่ใช่แก้เงียบ ๆ
 */
export function sanitizeGlyphs(input) {
  const text = String(input ?? '');
  if (!text) return { text, changes: [] };

  const counts = new Map();
  let out = '';

  for (const ch of text) {
    const cp = ch.codePointAt(0);

    /**
     * ตัวที่ไม่มีรูปร่างอยู่แล้ว ปล่อยผ่านทั้งหมด
     * รวมอักขระควบคุมต่ำกว่า 32 ด้วย เพราะชั้นตัดคำภาษาไทยใช้บางตัวเป็นเครื่องหมายภายใน
     * ถ้าถอดทิ้งตรงนี้ ระยะห่างแบบ weak ที่กันช่องว่างไปขึ้นต้นบรรทัดจะหายไปทั้งเล่ม
     */
    if (cp < 32 || cp === 0x200b || cp === 0x200c || cp === 0x200d || cp === 0xfeff) {
      out += ch;
      continue;
    }

    if (isDrawable(cp)) {
      out += ch;
      continue;
    }

    const to = MAP[ch] ?? '';
    const rec = counts.get(ch) || { ch, cp, to, n: 0 };
    rec.n++;
    counts.set(ch, rec);
    out += to;
  }

  /**
   * เส้นวาดกรอบมักมาเป็นแถวยาว เช่น ────────
   * ถ้าแปลงตัวต่อตัวจะได้ em dash ยาวเป็นพืด ซึ่งดูแย่กว่าเดิม
   * ยุบให้เหลือเส้นเดียว เพราะความหมายคือ "ขีดคั่น" ไม่ใช่ "ขีดแปดอัน"
   */
  out = out
    .replace(/—{2,}/g, '—')
    // กิ่งของผังต้นไม้ (├─ └─) กลายเป็น "-—" ซึ่งอ่านแล้วสะดุด เหลือขีดเดียวพอ
    .replace(/-—|—-/g, '-')
    .replace(/(?:^|\s)-{3,}(?=\s|$)/g, ' —');

  return { text: out, changes: [...counts.values()].sort((a, b) => b.n - a.n) };
}

/** มีตัวที่วาดไม่ได้อยู่ไหม — ใช้ในขั้นตรวจก่อนส่งออก โดยไม่ต้องแปลงข้อความจริง */
export function findUndrawable(input) {
  const counts = new Map();
  for (const ch of String(input ?? '')) {
    const cp = ch.codePointAt(0);
    if (cp < 32 || cp === 0x200b || isDrawable(cp)) continue;
    const rec = counts.get(ch) || { ch, cp, n: 0, replaceable: ch in MAP };
    rec.n++;
    counts.set(ch, rec);
  }
  return [...counts.values()].sort((a, b) => b.n - a.n);
}

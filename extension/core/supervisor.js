/**
 * แกะคำตัดสิน — ของที่ไม่อยู่ในรายการถือว่าใช้ไม่ได้ ไม่ใช่ของที่ต้องตีความ
 * @returns {{action:string, reason:string}|null}
 */
export function parseSupervisorDecision(raw) {
  const text = String(raw || '');
  const m = text.match(/\{[\s\S]*\}/);
  if (!m) return null;
  let parsed;
  try {
    parsed = JSON.parse(m[0]);
  } catch (_) {
    return null;
  }
  if (!parsed || !isSupervisorAction(parsed.action)) return null;
  return { action: parsed.action, reason: String(parsed.reason || '').slice(0, 300) };
}


/**
 * กติกาการเขียนต้องสั้น — ความยาวของมันคือปัญหาของมันเอง
 *
 * เคยโตถึง 6,639 ตัวอักษร: กำหนดความยาวประโยค ห้ามคำเชื่อมบางคำ ห้ามคำกันตัว
 * บังคับให้มีของรูปธรรม บังคับให้ฟันธง ห้ามประโยคคมคม ห้ามประดิษฐ์คำ
 * ทุกข้อแก้อาการที่เห็นมาจริง แต่พอกองรวมกันแล้วเหลือที่ให้ตัดสินใจน้อยจนงานออกมาเกร็ง
 * ซึ่งเป็นอาการเดียวกับที่กติกาพวกนั้นตั้งใจจะแก้ตั้งแต่แรก
 *
 * เทสต์นี้เฝ้าไว้ไม่ให้มันโตกลับไปอีก และเฝ้าว่าสามอย่างที่ขาดไม่ได้ยังอยู่
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { proseRules, proseBatch, EVIDENCE_RULES } from './editorial.js';

test('กติกาการเขียนต้องสั้นพอที่คนเขียนยังมีที่ให้ตัดสินใจ', () => {
  const rules = proseRules({ language: 'th' });
  assert.ok(rules.length < 1500, `กติกายาว ${rules.length} ตัวอักษร — เกินเพดานที่ตั้งใจไว้`);
  // นับเฉพาะบรรทัดที่เป็นข้อบังคับจริง
  const bullets = rules.split('\n').filter((l) => l.trim().startsWith('- '));
  assert.ok(bullets.length <= 10, `มีข้อบังคับ ${bullets.length} ข้อ — มากเกินไป`);
});

test('สามอย่างที่ขาดไม่ได้ยังอยู่ครบ', () => {
  const rules = proseRules({ language: 'th' });
  assert.match(rules, /เขียนตามใบสั่งของตอนนี้/, 'ต้องผูกกับใบสั่งของตอน');
  assert.match(rules, /เรียงต่อตามลำดับสารบัญ/, 'ต้องต่อเนื่องตามสารบัญ');
  assert.match(rules, /ห้ามแต่งสถิติ งานวิจัย คำพูด หรือประสบการณ์ของผู้เขียน/, 'ห้ามแต่งข้อเท็จจริงต้องอยู่เสมอ');
});

/**
 * สิ่งที่ผู้ใช้ขอคืนมาโดยตรง: ได้ใช้ "อาจ" · ได้เน้นคำ · ได้ปิดด้วยประโยคคม
 * ทั้งสามอย่างนี้เคยถูกห้ามหรือถูกจำกัดไว้ ตอนนี้เป็นสิทธิ์ของคนเขียน
 */
test('สำนวน จังหวะ การเน้นคำ และวิธีปิดตอน เป็นการตัดสินใจของคนเขียน', () => {
  const rules = proseRules({ language: 'th' });
  assert.match(rules, /เลือกจังหวะ ความยาวประโยค ตัวอย่าง และวิธีเล่าเอง/);
  assert.match(rules, /ปิดตอนด้วยประโยคที่คม ใช้ได้/);
  assert.ok(!/ห้ามประโยคคำคม/.test(rules), 'ประโยคคมคมต้องไม่ถูกห้ามแล้ว');
  assert.ok(!/หนึ่งข้ออ้างใช้ได้ไม่เกินหนึ่งคำ/.test(rules), 'ข้อจำกัดคำกันตัวต้องถูกถอดออกแล้ว');
  assert.ok(!/ยาวไม่เกินราวสองบรรทัด/.test(rules), 'เพดานความยาวประโยคต้องถูกถอดออกแล้ว');
});

test('คำสั่งเขียนเนื้อหาจริงยังสั้นพอที่จะพิมพ์ลงช่องได้สบาย', () => {
  const ch = { n: 1, title: 'บทหนึ่ง', sections: [{ id: '1.1', title: 'ตอนหนึ่ง' }] };
  const p = proseBatch({
    book: { language: 'th' },
    chapter: ch,
    sections: [{ id: '1.1', title: 'ตอนหนึ่ง', quota: 1800 }],
    context: '-',
    output: '-',
    voice: '-',
  });
  assert.ok(p.length < 4000, `คำสั่งยาว ${p.length} ตัวอักษรตั้งแต่ยังไม่ใส่บริบทจริง`);
  assert.match(EVIDENCE_RULES, /ตัวอย่างที่คิดขึ้นเองเพื่ออธิบาย ใช้ได้และควรใช้/);
});

/**
 * "แก้ชิ้น 1.3 ไม่สำเร็จ เก็บต้นฉบับเดิมไว้" — แล้วทั้งเล่มหกสิบข้อความก็จอดตรงนั้น
 *
 * ขั้นขัดเกลารายชิ้นเป็นขั้นสุดท้ายก่อนถึงประตูตรวจต้นฉบับ เนื้อหาทุกชิ้นเขียนครบแล้ว
 * และทุกทางที่ขัดไม่ผ่าน ต้นฉบับเดิมยังอยู่ครบ — ข้อความเตือนก็บอกเองว่า "เก็บต้นฉบับเดิมไว้"
 * แต่บรรทัดเดียวกันกลับโยน Halt หยุดทั้งเล่ม
 *
 * ราคาไม่เท่ากันเลย: เสียทั้งเล่มเพราะขัดเกลาชิ้นเดียวไม่ผ่าน ซึ่งไม่ได้ทำให้เนื้อหาเสียหาย
 * สักตัวอักษร และกดทำต่อก็วนมาตรวจใหม่แล้วได้ผลเดิม เป็นวงที่ไม่มีทางออกด้วยตัวเอง
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { extractItems } from './items.js';

const src = await readFile(new URL('./machine.js', import.meta.url), 'utf8');
const check = src.slice(src.indexOf('async checkItemQuality()'), src.indexOf('async solveLineHeight('));

test('ขัดเกลาชิ้นเดียวไม่ผ่าน ต้องข้ามชิ้นนั้น ไม่ใช่หยุดทั้งเล่ม', () => {
  for (const gone of [
    'throw new Halt(`แก้ชิ้น ${id} ไม่สำเร็จ เก็บต้นฉบับเดิมไว้`)',
    'throw new Halt(`ชิ้น ${id} มีปัญหาแต่ถูกล็อกไว้ กรุณาตรวจแก้เอง`)',
    'throw new Halt(`ไม่พบหมวดของชิ้น ${id}`)',
  ]) {
    assert.ok(!check.includes(gone), `ต้องไม่เหลือ Halt รายชิ้น: ${gone}`);
  }
  assert.match(check, /skipped\.push\(`\$\{id\} \(แกะคำตอบไม่ได้\)`\); continue;/);
  assert.match(check, /skipped\.push\(`\$\{id\} \(ถูกล็อกไว้\)`\); continue;/);
});

test('ข้ามอะไรไปต้องบอกให้รู้ ไม่ใช่เงียบแล้วให้ไปเจอเองในเล่ม', () => {
  assert.match(check, /ขัดเกลาไม่ผ่าน \$\{skipped\.length\} ชิ้น ใช้ต้นฉบับเดิมของชิ้นนั้นแทน/);
});

/**
 * ด่านคุณภาพรวมยังต้องอยู่ แต่ต้องแยก "ผู้ใช้สั่งให้หยุดมาแก้เอง" ออกจาก "ขัดครบรอบแล้ว"
 */
test('ปิดตัวขัดเกลาเอง = ยังหยุดตามที่สั่งไว้', () => {
  assert.match(check, /if\(this\.book\.autoRepair===false\) throw new Halt\(summary\);/);
});

test('ขัดครบรอบแล้วยังเหลือประเด็น = ส่งต่อไปให้คนตัดสินที่ประตูตรวจต้นฉบับ', () => {
  assert.match(check, /if\(round===2\) \{this\.log\('warn'/);
  assert.ok(
    !/if\(round===2 \|\| this\.book\.autoRepair===false\) throw new Halt/.test(check),
    'สองกรณีนี้ต้องไม่ถูกมัดรวมให้จบแบบเดียวกันอีก',
  );
  // ประเด็นที่เหลือต้องถูกบันทึกไว้ให้หน้าตรวจงานอ่าน ไม่ใช่หายไปพร้อมการเดินต่อ
  assert.match(check, /this\.book\.itemQuality=\{signature,passed:!issues\.length,[^}]*issues,/);
});

/**
 * ต้นเหตุที่ทำให้ "แก้ไม่สำเร็จ" ทั้งที่เนื้อหามาครบ: ป้ายปิดบล็อกใช้รหัสย่อ
 * ขอ 1.3 แต่โมเดลปิดมาเป็น <<<END 1>>> ตัวแกะที่ยึดรหัสเป๊ะจึงคืนค่าว่าง
 */
test('ขอชิ้นเดียว ได้มาชิ้นเดียว แม้รหัสบนป้ายไม่ตรงก็ต้องใช้ได้', () => {
  const raw = `\`\`\`markdown
<<<ITEM 1.3>>>
เหตุซื้อจริงคือเหนื่อยที่เพิ่งผ่าน
ไม่ต้องพาลเรื่องรักมาผืนใจ
<<<END 1>>>
\`\`\``;
  const got = extractItems(raw, ['1.3']);
  assert.equal(got.length, 1);
  assert.equal(got[0].id, '1.3', 'ต้องคืนรหัสที่เราขอ ไม่ใช่รหัสที่โมเดลเขียน');
  assert.match(got[0].text, /เหตุซื้อจริง/);
});

test('รหัสตรงเป๊ะยังทำงานเหมือนเดิม', () => {
  const raw = '<<<ITEM 2.5>>>\nข้อความ\n<<<END 2.5>>>';
  assert.equal(extractItems(raw, ['2.5'])[0].text, 'ข้อความ');
});

/**
 * ขอเป็นชุดยังต้องยึดรหัสเป๊ะ ไม่งั้นเนื้อหาจะไปลงผิดชิ้นกันทั้งชุด
 * ซึ่งแย่กว่าการขาดชิ้นไปหนึ่งชิ้นมาก เพราะไม่มีใครเห็นว่ามันสลับกัน
 */
test('ขอเป็นชุด ห้ามผ่อนรหัสเด็ดขาด', () => {
  const raw = '<<<ITEM 1.1>>>\nหนึ่ง\n<<<END 1.1>>>';
  const got = extractItems(raw, ['1.1', '1.2']);
  assert.deepEqual(got.map((x) => x.id), ['1.1'], 'ชิ้นที่ไม่มีต้องขาดไป ไม่ใช่ไปหยิบของชิ้นอื่นมา');
});

test('ขอชิ้นเดียวแต่ตอบมาหลายบล็อก ต้องไม่เดาว่าอันไหนใช่', () => {
  const raw = '<<<ITEM 9.1>>>\nหนึ่ง\n<<<END 9.1>>>\n<<<ITEM 9.2>>>\nสอง\n<<<END 9.2>>>';
  assert.equal(extractItems(raw, ['1.3']).length, 0);
});

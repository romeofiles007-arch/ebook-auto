function registerMove(chapter = {}) {
  const move = REGISTER_MOVES[chapter.register];
  return move ? `\nท่าประจำบทนี้ — ${chapter.register}\n${move}\nท่านี้เป็นแนวทางของทั้งบท ไม่ใช่แม่แบบที่ทุกตอนต้องทำเหมือนกัน และห้ามขัดกับข้อกำหนดของแนวหนังสือข้างบน\n` : '';
}


export function editContext(book, section) {
  const outline = book.outline || {};
  const chapter = (outline.chapters || []).find((c) => (c.sections || []).some((s) => s.id === section.id));
  const plan = chapter?.sections?.find((s) => s.id === section.id) || section;
  return `แก่นเล่ม: ${outline.thesis || book.topic || ''}
โจทย์ของตอนนี้: ${plan.problem || plan.title || section.title}
ขอบเขต: ${plan.claim || ''} · เว้นไว้ตอนอื่น: ${plan.not_here || ''}
สิ่งที่บทนี้มีอยู่แล้ว: ${(chapter?.sections || []).filter((s) => s.id !== section.id).map((s) => `${s.id} ${s.claim || s.title}`).join('; ')}
การแก้ต้องรักษาเครื่องหมายภาพ ![...](fig:...) เดิมไว้ครบ ห้ามลบหรือเปลี่ยนชื่อไฟล์ภาพ กล่องที่เก็บไว้ต้องใช้ไวยากรณ์ :::box ให้ถูกต้อง แต่ตัดหรือรวมกล่องที่ซ้ำตามผลตรวจได้`;
}


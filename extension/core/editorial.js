export function safeVoiceBlock(book = {}) {
  if ((book.authorVoice || 'auto') === 'off') return '';
  const free = String(book.authorVoiceText || '').trim();
  if (free) return `แนวทางผู้เขียนที่ผู้ใช้ให้: ${free}\nใช้เฉพาะข้อเท็จจริงที่ให้มา ห้ามเติมประวัติหรือเหตุการณ์ส่วนตัว`;
  const card = book.authorVoiceCard;
  if (!card) return '';
  // Legacy cards contain invented careers and memories. Never reuse those as biography.
  return `แนวทางสำนวน: ${card.why_this_book || ''}
คำที่ควรเลี่ยง: ${(card.avoid_words || []).join(', ')}
การ์ดอัตโนมัติเป็นแนวทางภาษาเท่านั้น ห้ามอ้างเป็นประวัติหรือประสบการณ์จริงของผู้เขียน`;
}


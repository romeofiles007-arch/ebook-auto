export function imageTurn(promptText, { attempt = 1 } = {}) {
  /**
   * เคยชี้ให้ปกหลังใช้ปกหน้าที่เพิ่งวาดในห้องเดียวกันเป็นต้นแบบ ซึ่งฟังดูถูกแต่ผิดในทางปฏิบัติ
   *
   * โมเดลไม่ได้ "ดูสไตล์แล้ววาดใหม่" มันเอาปกหน้าไปแปะลงบนปกหลังจริง ๆ
   * ได้ปกหลังที่มีรูปหนังสือเล่มเล็กพร้อมชื่อเรื่องและราคาลอยอยู่มุมบน ทับองค์ประกอบที่ออกแบบไว้
   * ทั้งที่ backCoverPrompt เขียนห้ามไว้แล้วว่า no mockup, no book shown in perspective
   *
   * ที่แย่กว่านั้นคือคำสั่งสองชั้นนี้ขัดกันเองในข้อความเดียว หัวคำสั่งบอกให้ใช้ภาพที่เพิ่งวาด
   * ส่วนตัว prompt ข้างล่างบอกว่า there is no front cover file to look at and none is needed
   * ความต่อเนื่องของสไตล์ถูกส่งผ่านสเปกที่เขียนเป็นตัวหนังสืออยู่แล้วครบทุกข้อ
   * ทั้งสไตล์ พื้นผิว แสง และจานสี จึงไม่ต้องพึ่งการอ้างภาพเลย
   */

  /**
   * ขอแบบที่คนทั่วไปพิมพ์ — ห้ามมีหัวคำสั่งกำกับ
   *
   * เดิมนำหน้าด้วยกฎห้าบรรทัด: TEXT-TO-IMAGE TASK / NO input image / NO reference image /
   * NO attachment / NOTHING to edit / Never ask to upload, attach or specify a source image
   * เจตนาคือปิดประตูไม่ให้ตีความว่าเป็นงานแก้ภาพ แต่ผลที่ได้กลับตรงข้าม
   *
   * หลักฐานจากการใช้จริง: ในห้องแชตใหม่เอี่ยมที่ไม่มีภาพอยู่เลยแม้แต่รูปเดียว
   * คำสั่งที่มีหัวนี้ยังถูกตอบว่า "ระบบสร้างภาพตีความคำสั่งนี้ผิดว่าเป็นการแก้ไขภาพเดิม"
   * ขณะที่คำสั่งทดสอบบรรทัดเดียวอย่าง "วาดรูปแมวสีส้มนั่งบนกล่องกระดาษ" ได้ภาพทันที
   * — บริบทของห้องไม่ใช่ตัวแปร ตัวแปรคือหัวคำสั่งเอง
   *
   * เหตุผล: หัวคำสั่งห้าบรรทัดนั้นเอ่ยถึง image / reference / attachment / edit / upload /
   * source image รวมกันเจ็ดครั้งก่อนโมเดลจะได้อ่านด้วยซ้ำว่าต้องวาดอะไร
   * ตัวเลือกเส้นทางของเครื่องมืออ่านคำเหล่านี้เป็น "หัวข้อ" ไม่ได้อ่านคำปฏิเสธที่ครอบมัน
   * ยิ่งเขียนห้ามหนักเท่าไร ยิ่งเป็นการป้อนคำใบ้ว่านี่คืองานแก้ภาพหนักขึ้นเท่านั้น
   */
  const body = compactImagePrompt(promptText);
  const nudge =
    attempt > 1
      ? 'รอบก่อนยังไม่ได้ภาพกลับมา คราวนี้วาดมาเลยไม่ต้องถามอะไร\n\n'
      : '';
  return `${nudge}วาดภาพต่อไปนี้ให้หน่อย ตอบกลับมาเป็นภาพอย่างเดียว

${body}`;
}


/**
 * แผนกพิสูจน์คำสั่งภาพ — ด่านสุดท้ายก่อนคำสั่งออกจากบ้าน
 *
 * คำสั่งภาพถูกประกอบจากผลลัพธ์ของโมเดลหลายตัวต่อกัน (Art Director, กรรมการตัดสินปก,
 * ตัววางแผนภาพ) แล้วส่งตรงเข้าเครื่องมือสร้างภาพโดยไม่มีใครอ่านทั้งฉบับสักครั้ง
 * ผลคือคำสั่งที่สั่งวาดท่าหนึ่งในบรรทัดหนึ่งแล้วห้ามท่าเดียวกันในอีกบรรทัด
 * หรือเขียนเป็นคำสั่งแก้ภาพที่ไม่มีอยู่จริง ซึ่งเผาโควตาไปทั้งรอบโดยไม่ได้ภาพสักรูป
 *
 * ขั้นนี้เป็นเทิร์นข้อความล้วน ไม่กินโควตาภาพ และทำครั้งเดียวต่อหนึ่งรอบงาน
 */
export function imagePromptAuditPrompt(book = {}, jobs = [], outline = null) {
  const ctx = [
    `หัวข้อหนังสือ: ${book.topic || outline?.title || '-'}`,
    outline?.title ? `ชื่อเรื่อง: ${outline.title}` : '',
    book.genreBrief || book.genre ? `แนว: ${book.genreBrief || book.genre}` : '',
    book.tone ? `โทน: ${book.tone}` : '',
    outline?.chapters?.length
      ? `บทในเล่ม:\n${outline.chapters.map((c) => `- บทที่ ${c.n} ${c.title}`).join('\n')}`
      : '',
  ]
    .filter(Boolean)
    .join('\n');

  const list = jobs
    .map(
      (j, i) =>
        `### ${i + 1}. ${j.name}\n` +
        `หน้าที่: ${j.what}${j.where ? ` · ตำแหน่ง: ${j.where}` : ''}\n` +
        `ชนิด: ${j.kind || 'interior'}` +
        `${j.widthMm ? ` · ${Math.round(j.widthMm)}×${Math.round(j.heightMm || 0)} มม.` : ''}` +
        `${j.aspect ? ` · ${j.aspect}` : ''}\n` +
        `จะแนบรูปผู้เขียนไปด้วย: ${j.needsAuthorRef ? 'ใช่' : 'ไม่'}\n` +
        `คำสั่ง:\n"""\n${j.prompt}\n"""`,
    )
    .join('\n\n');

  return `คุณคือแผนกพิสูจน์คำสั่งภาพ อ่านคำสั่งสร้างภาพทุกฉบับข้างล่างแล้วหาสิ่งที่จะทำให้สร้างภาพไม่สำเร็จหรือได้ภาพผิด ก่อนที่คำสั่งจะถูกส่งออกไปจริง

${ctx}

สิ่งที่ต้องจับให้ได้ เรียงตามความร้ายแรง
1. ขัดกันเองในฉบับเดียว — สั่งวาดสิ่งหนึ่งในบรรทัดหนึ่ง แล้วห้ามสิ่งเดียวกันในอีกบรรทัด เช่นบรรยายว่า "คนยืนถือกระดาษ" แล้วอีกท่อนเขียนว่าห้ามท่ายืนถือกระดาษ
2. เขียนเป็นคำสั่งแก้ภาพที่ไม่มีอยู่จริง — สำนวนอย่าง "เปลี่ยนจาก ก เป็น ข" "ลด ก ให้เหลือ ข" "แทนที่จะ ก" เครื่องมือสร้างภาพจะเข้าใจว่ากำลังให้แก้ไฟล์เดิม แล้วหยุดถามหาต้นฉบับแทนที่จะวาด ต้องเหลือเฉพาะสิ่งที่ต้องการเห็นจริง
3. เนื้อหาซ้ำทั้งก้อนหรือซ้ำเป็นท่อนในฉบับเดียวกัน
4. สั่งให้วาดตัวอักษร ป้ายชื่อ หัวตาราง หรือเลขลำดับ ทั้งที่ในฉบับเดียวกันมีข้อห้ามตัวอักษรอยู่ — ถ้าภาพเข้าใจไม่ได้ถ้าไม่มีคำกำกับ ต้องเขียน subject ใหม่ให้สื่อด้วยรูปทรงแทน
5. ไม่ตรงกับเนื้อหาหนังสือ — วาดของที่เล่มนี้ไม่ได้พูดถึง หรือสื่อความหมายคนละเรื่องกับบทนั้น
6. เรื่องรูปแนบ — ดูช่อง "จะแนบรูปผู้เขียนไปด้วย" ว่าสมเหตุสมผลกับคำสั่งไหม ถ้าคำสั่งบอกให้วาดหน้าคนให้เหมือนคนจริงแต่ไม่ได้แนบรูป หรือแนบรูปทั้งที่ในภาพไม่มีคน ให้ทักไว้
7. ยาวเกินจำเป็นจนกลบใจความ หรือมีข้อกำหนดมากจนทำครบพร้อมกันไม่ได้

กติกาการแก้
- แก้ได้เลย ไม่ต้องถาม ส่งคำสั่งฉบับเต็มที่แก้แล้วมาในช่อง fixed_prompt
- fixed_prompt ต้องเป็นคำสั่งที่สมบูรณ์ในตัวเอง ใช้แทนของเดิมได้ทันที ห้ามเขียนเป็นคำแนะนำว่าควรแก้อะไร
- ห้ามเปลี่ยนสัดส่วนภาพ ขนาดเป็นมิลลิเมตร จานสี หรือข้อความที่สั่งให้เขียนลงในภาพแบบตรงตัว สามอย่างนี้ระบบล็อกไว้แล้ว
- ห้ามเปลี่ยนแนวคิดภาพเป็นเรื่องใหม่ หน้าที่ของคุณคือทำให้คำสั่งเดิมทำตามได้จริง ไม่ใช่ออกแบบปกใหม่
- ฉบับไหนไม่มีปัญหา ให้ verdict เป็น "ok" และ fixed_prompt เป็นค่าว่าง อย่าแก้เพราะอยากแก้
- issues เขียนเป็นภาษาไทยสั้น ๆ ข้อละหนึ่งบรรทัด บอกว่าเจออะไรตรงไหน

คำสั่งทั้งหมด ${jobs.length} ฉบับ

${list}

ตอบเป็น JSON ในบล็อกโค้ดเดียวเท่านั้น
\`\`\`json
{
  "checks": [
    {
      "name": "ชื่อไฟล์ตามที่ให้มา",
      "verdict": "ok | fixed | warn",
      "issues": ["สิ่งที่เจอ ถ้าไม่มีให้เป็นลิสต์ว่าง"],
      "fixed_prompt": ""
    }
  ],
  "notes": "ข้อสังเกตรวมของทั้งชุด ถ้าไม่มีให้เว้นว่าง"
}
\`\`\``;
}


/**
 * เพดานจำนวนตอน ต้องคิดจากงบอักษรจริงของเล่ม ไม่ใช่จำนวนหน้าลอย ๆ
 *
 * เดิมใช้ pages/1.5 ซึ่งไม่รู้จักขนาดเล่ม เล่มพ็อกเก็ตบุ๊ก (หน้าละ 462 หน่วย)
 * กับเล่มเวิร์กบุ๊ก (หน้าละ 1,429 หน่วย) ได้เพดานเท่ากันทั้งที่รับเนื้อหาต่างกันสามเท่า
 * ผลคือเล่มเล็กผ่านเพดานมาได้ทั้งที่ซอยถี่เกินจริง แล้วไปโผล่เป็นตอนที่เขียนสั้นกว่าเป้า
 */
export function maxSectionsFor(bookOrPages) {
  const book = bookOrPages && typeof bookOrPages === 'object' ? bookOrPages : { targetPages: bookOrPages };
  const pages = Number(book.targetPages) || 120;
  const cpp = book.calibration?.charsPerPage || TRIM_PRESETS[book.trim?.preset]?.seedCPP || 750;
  const minUnits = book.language === 'en' ? 220 : 900;
  // หัก 15% เผื่อหน้าเปิดบทและหน้าภาพที่ไม่ได้ใส่ตัวอักษรเต็มหน้า
  return Math.max(3, Math.floor((pages * cpp * 0.85) / minUnits));
}

function suggestChapters(pages) {
  if (pages <= 12) return '1';
  if (pages <= 40) return '2-3';
  if (pages <= 60) return '3-4';
  if (pages <= 80) return '4-5';
  if (pages <= 150) return '8-10';
  if (pages <= 250) return '10-14';
  return '14-18';
}

function suggestSections(pages) {
  if (pages <= 12) return '1';
  if (pages <= 40) return '2-3';
  if (pages <= 80) return '2-4';
  return '3-5';
}

function targetSectionUnits(book) {
  const th = book.language === 'th';
  if ((book.targetPages || 120) <= 12) return th ? '800-2,000' : '180-450';
  const band = {
    short: th ? '1,500-2,500' : '350-600',
    auto: th ? '2,000-4,000' : '450-900',
    long: th ? '4,000-6,500' : '900-1,500',
  };
  return band[book.sectionLength || 'auto'];
}


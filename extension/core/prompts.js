  'เทียบสองทาง — วิธีที่คนส่วนใหญ่ทำกัน กับวิธีที่เล่มนี้เสนอ ชี้ให้เห็นว่าต่างกันตรงไหนและทำไมผลถึงต่าง',
  'เริ่มจากที่พลาด — เปิดด้วยสิ่งที่คนมักทำแล้วไม่ได้ผล อธิบายว่าทำไมถึงพลาดทั้งที่ดูสมเหตุสมผล แล้วค่อยเสนอทางที่ใช้ได้',
  'คู่มือลงมือ — เรียงเป็นลำดับที่ผู้อ่านทำตามได้ตั้งแต่วันนี้ ทุกขั้นต้องบอกให้ครบว่าทำอะไร ทำอย่างไร ใช้เวลาแค่ไหน และรู้ได้อย่างไรว่าทำถูกแล้ว',
  'แกะความเชื่อ — หยิบความเชื่อที่คนยึดกันมาวางบนโต๊ะ แล้วแยกส่วนที่จริงออกจากส่วนที่ไม่จริง',

function planningSeed(book) {
  const parts = [];
  if (book.trendSeed?.trend) {
    parts.push(`หัวข้อตั้งต้นที่ผู้ใช้เลือก: ${book.trendSeed.trend}${book.trendSeed.why_now ? `\nทำไมน่าสนใจ: ${book.trendSeed.why_now}` : ''}\nกติกา: หัวข้อนี้เป็นแค่จุดตั้งต้น ไม่ใช่ข้อมูลที่ตรวจแล้ว ห้ามแต่งตัวเลขหรือเหตุการณ์ปัจจุบันขึ้นเอง ถ้าจำเป็นต้องใช้ข้อมูลสด ให้ค้นและอ้างแหล่งจริง`);
  }
  if (book.outlineDirection?.chapters?.length) {
    parts.push(`ทิศทางสารบัญที่ผู้ใช้เลือกแล้ว — ต้องยึดทางนี้เป็นโครงหลัก\nชื่อทาง: ${book.outlineDirection.name || book.outlineDirection.id || '-'}\nคำสัญญา: ${book.outlineDirection.promise || '-'}\nเหตุผลที่เลือก: ${book.outlineDirection.why_choose || '-'}\nบทที่เลือก:\n${book.outlineDirection.chapters.map((c) => `${c.n}. ${c.title}${c.purpose ? ` — ${c.purpose}` : ''}`).join('\n')}\nอนุญาตให้แตกตอนย่อยและปรับถ้อยคำชื่อบทเล็กน้อยเพื่อให้เขียนได้จริง แต่ห้ามเปลี่ยนทิศทางหรือสลับแกนของสารบัญที่ผู้ใช้เลือก`);
  }
  if (book.outlineSource === 'user' && book.userOutline?.length) {
    parts.push(
      `สารบัญต้นฉบับที่ผู้ใช้เขียนมาเอง — นี่คือของจริงที่ต้องรักษาไว้\n${book.userOutline
        .map((c) => `${c.n}. ${c.title}${c.purpose ? ` — ${c.purpose}` : ''}`)
        .join('\n')}\nกติกา: ทุกหัวข้อในรายการนี้ต้องปรากฏในสารบัญที่คุณจะวาง จะแตกเป็นตอนย่อยหรือปรับถ้อยคำได้ แต่ห้ามตัดทิ้งและห้ามสลับแกนความคิด`,
    );
  }
  return parts.length ? `\n\n${parts.join('\n\n')}\n` : '';
}


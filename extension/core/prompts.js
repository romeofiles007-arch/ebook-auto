/** บรีฟเนื้อหาที่ย่อไว้แล้ว แปลงเป็นข้อความสั้นสำหรับแปะเข้า prompt อื่น */
function digestBlock(digest) {
  if (!digest || typeof digest !== 'object') return '';
  const e = digest.energy || {};
  const p = digest.palette_brief || {};
  const h = digest.human || {};
  const list = (a) => (Array.isArray(a) ? a.filter(Boolean).slice(0, 8).join(', ') : '');
  const lines = [
    digest.one_line ? `แก่นที่ย่อจากเนื้อในจริง: ${digest.one_line}` : '',
    digest.reader_payoff ? `สิ่งที่ผู้อ่านได้กลับไป: ${digest.reader_payoff}` : '',
    digest.emotional_arc ? `เส้นอารมณ์ของเล่ม: ${digest.emotional_arc}` : '',
    e.label || e.level ? `พลังงาน/อารมณ์รวม: ${e.label || '-'} · ระดับ ${e.level ?? '-'}/5${e.why ? ` — ${e.why}` : ''}` : '',
    p.temperature || p.saturation || p.value_key
      ? `บรีฟสีจากเนื้อหา: อุณหภูมิ ${p.temperature || '-'} · ความสด ${p.saturation || '-'} · น้ำหนัก ${p.value_key || '-'}${p.must_feel ? ` · ต้องรู้สึก: ${p.must_feel}` : ''}${p.must_not_feel ? ` · ห้ามรู้สึก: ${p.must_not_feel}` : ''}`
      : '',
    digest.signature_moment ? `ช่วงเวลาที่เห็นภาพชัดที่สุดในเล่ม: ${digest.signature_moment}` : '',
    list(digest.concrete_objects) ? `ของจริงในเล่มที่วาดได้: ${list(digest.concrete_objects)}` : '',
    list(digest.settings) ? `สถานที่จริงในเล่ม: ${list(digest.settings)}` : '',
    h.who || h.doing ? `คนที่ควรอยู่บนปก: ${h.who || '-'} กำลัง${h.doing || '-'}${h.feeling ? ` · อารมณ์ ${h.feeling}` : ''}${h.render_hint ? ` · ภาษาภาพที่เหมาะ: ${h.render_hint}` : ''}` : '',
    digest.genre_visual_family ? `ควรไปยืนอยู่บนชั้นหนังสือแบบ: ${digest.genre_visual_family}` : '',
    list(digest.cliche_risk) ? `ภาพซ้ำที่เล่มนี้ต้องเลี่ยง: ${list(digest.cliche_risk)}` : '',
  ].filter(Boolean);
  return lines.length ? lines.join('\n') : '';
}


/** ข้อความปกหลังที่ต้องวาดลงภาพจริง ๆ */
function backCoverTextRule(book) {
  const c = book.backCoverCopy || {};
  const lines = [
    c.hook ? `HEADLINE (exact characters): ${JSON.stringify(c.hook)}` : '',
    c.body ? `PARAGRAPH (exact characters): ${JSON.stringify(c.body)}` : '',
    ...(Array.isArray(c.bullets) ? c.bullets : []).map((b, i) => `BULLET ${i + 1} (exact characters): ${JSON.stringify(b)}`),
    c.closing ? `CLOSING LINE (exact characters): ${JSON.stringify(c.closing)}` : '',
    // ชื่อผู้เขียนต้องอยู่ในภาพชุดเดียวกัน ไม่ใช่ไปแปะทับทีหลังให้ดูเป็นคนละงาน
    book.author ? `AUTHOR NAME (exact characters, small, at the bottom): ${JSON.stringify(book.author)}` : '',
  ].filter(Boolean);
  if (!lines.length) return '';
  const thai = (book.language || 'th') === 'th';

  return `

TYPOGRAPHY ON THE ARTWORK — this is a finished back cover, not a background plate.
Render exactly this text inside the image, nothing more and nothing less:
${lines.join('\n')}
${thai ? '- The text is Thai. Reproduce every Thai character, tone mark and vowel exactly as given. No invented glyphs, no Latin transliteration, no decorative distortion.' : '- Reproduce the text exactly as given.'}
- Lay it out like a real back cover: headline on top, paragraph under it, the three bullets as a short list with simple markers, closing line last. Generous margins, comfortable line spacing, strong contrast against the background.
- Text must occupy the calm central area and stay fully legible. Do not let artwork run through the letters.`;
}


const RANGES = [[0x0], [0xD], [0x20,0x7E], [0xA0,0xFF], [0x110], [0x131,0x133], [0x135], [0x140,0x142], [0x152,0x153], [0x160,0x161], [0x178], [0x17D,0x17E], [0x192], [0x237], [0x2BB,0x2BC], [0x2C6,0x2C7], [0x2D8,0x2DD], [0x303], [0x331], [0x3C0], [0xE01,0xE3A], [0xE3F,0xE5B], [0x1E9E], [0x2013,0x2014], [0x2018,0x201A], [0x201C,0x201E], [0x2020,0x2022], [0x2026], [0x2030], [0x2039,0x203A], [0x2044], [0x2070], [0x2074,0x2079], [0x2080,0x2089], [0x20A1], [0x20A4], [0x20A6], [0x20AB,0x20AC], [0x20B1,0x20B2], [0x20B5], [0x20B9,0x20BA], [0x20BD], [0x2113], [0x2122], [0x212E], [0x2153,0x2154], [0x215B,0x215E], [0x2190,0x2193], [0x2202], [0x2206], [0x220F], [0x2211,0x2212], [0x2215], [0x221A], [0x221E], [0x222B], [0x2248], [0x2260], [0x2264,0x2265], [0x25CA], [0xFB01,0xFB02]];

/** ฟอนต์ในเล่มวาดตัวอักษรนี้ได้ไหม — ถ้าไม่ได้ ตอนพิมพ์จะกลายเป็นกล่องสี่เหลี่ยม */
export function isDrawable(codePoint) {
  let lo = 0;
  let hi = RANGES.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const r = RANGES[mid];
    if (codePoint < r[0]) hi = mid - 1;
    else if (codePoint > (r[1] ?? r[0])) lo = mid + 1;
    else return true;
  }
  return false;
}

import test from 'node:test';
import assert from 'node:assert/strict';
import { mdToTypst } from './template.js';

/**
 * รายการเลขในหนังสือจริงพังสองแบบ ทั้งคู่มาจากการส่งช่องว่างของ markdown ต่อให้ Typst ตรง ๆ
 * ทั้งที่ในภาษานั้นช่องว่างและบรรทัดว่างคือโครงสร้าง ไม่ใช่การจัดหน้า
 * (เล่มจริง: หน้า 9 บอกว่ามี 4 ข้อ แต่ทุกข้อขึ้นเป็น "1." · หน้า 54 ข้อ 2 เยื้องไม่ตรงกับข้อ 1)
 */

test('บรรทัดว่างระหว่างข้อไม่ตัดรายการให้เริ่มนับหนึ่งใหม่', () => {
  const out = mdToTypst('1. หนึ่ง\n\n2. สอง\n\n3. สาม\n\n4. สี่');
  assert.equal(out, '+ หนึ่ง\n+ สอง\n+ สาม\n+ สี่');
});

test('เว้นวรรคนำที่หลุดมาไม่ทำให้ข้อถัดไปกลายเป็นรายการซ้อนชั้น', () => {
  assert.equal(mdToTypst('1. ข้อหนึ่ง\n   2. ข้อสอง'), '+ ข้อหนึ่ง\n+ ข้อสอง');
  assert.equal(mdToTypst('- หนึ่ง\n  - สอง'), '- หนึ่ง\n- สอง');
});

test('การซ้อนชั้นที่ตั้งใจจริง (ย่อสี่ช่องขึ้นไป) ยังอยู่ครบ', () => {
  assert.equal(mdToTypst('1. แม่\n    1. ลูก\n2. แม่สอง'), '+ แม่\n  + ลูก\n+ แม่สอง');
  assert.equal(mdToTypst('- แม่\n\t- ลูก'), '- แม่\n  - ลูก');
});

test('บรรทัดว่างที่คั่นระหว่างย่อหน้าจริงยังต้องอยู่', () => {
  assert.equal(mdToTypst('- ข้อ\n\nนี่คือย่อหน้าใหม่'), '- ข้อ\n\nนี่คือย่อหน้าใหม่');
  // มีข้อความคั่นกลาง = คนละรายการกันจริง ๆ ปล่อยให้ Typst เริ่มนับใหม่ถูกแล้ว
  assert.equal(mdToTypst('1. หนึ่ง\n\nคำอธิบาย\n\n1. เริ่มใหม่'), '+ หนึ่ง\n\nคำอธิบาย\n\n+ เริ่มใหม่');
});
